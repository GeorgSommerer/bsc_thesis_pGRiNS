def grins_racipe_to_adata(grn_file, path_to_data : str, split_sinks : bool = False, replicate : int = 1, pert_list : list = []) -> ad.AnnData:
    """
    Takes a .parquet file containing the steady states generated by GRiNS-Racipe and turns it into an AnnData object.
    Do note that the steady state entries in grins_data.X are not discrete. 

    Parameters:
    -----------
    path_to_data : str
        A path to the file name of the data generated by GRiNS, without the name extension (.parquet, .csv, .h5ad, ...).
    pert_list : list, optional
        A list of dictionaries for each perturbation set, if applicable.
    max_missingness : float, optional
        The maximal percentage of cells for each gene that should be able to be missing.
    expon_scale : float, optional
        The scale of the exponential distribution used for missingness sampling.
    full_dropouts : float, optional
        How many genes should have 100% missingness.

    Returns:
    --------
    grins_data : ad.AnnData
        An AnnData object containing the GRiNS steady state solutions.
    """
    if split_sinks:
        sol_df = pd.concat([pd.read_parquet(f"{path_to_data}_ctrl.parquet"),pd.read_parquet(f"{path_to_data}_sinks_ctrl.parquet")],axis=1)
    else:
        sol_df = pd.read_parquet(f"{path_to_data}_ctrl.parquet")
    if pert_list != []:
        print("Loading perturbed data...")
        with open(f'Data/Projects/{grn_file}/{replicate:03}/ctrl_best_cells.pickle', 'rb') as f:
            best_cells = pickle.load(f)
            best_cell_tups = [(int(cell.split("_")[1]),int(cell.split("_")[2])) for cell in best_cells]
        # Keep cells where (InitCondNum,ParamNum) is in best_cells:
        tuples_in_df = pd.MultiIndex.from_frame(sol_df[["InitCondNum","ParamNum"]])
        sol_df = sol_df[tuples_in_df.isin(best_cell_tups)]
        if split_sinks:
            pert_sol_df = pd.concat([pd.read_parquet(f"{path_to_data}_pert.parquet"),pd.read_parquet(f"{path_to_data}_sinks_pert.parquet")],axis=1)[sol_df.columns] # Remove source genes not in adata from pert_df
        else:
            pert_sol_df = pd.read_parquet(f"{path_to_data}_pert.parquet")[sol_df.columns]
        sol_df = pd.concat([sol_df,pert_sol_df],axis=0,ignore_index=True)
        del pert_sol_df

    info_df = sol_df.loc[:,["PertNum","InitCondNum","ParamNum","SteadyStateFlag","Time"]].astype(int) # Contains combination of ICs and params and perts
    sol_df = sol_df.loc[:,[col for col in list(sol_df.columns) if ("gk_" not in col) & (col not in list(info_df.columns))]] # Remove all columns not containing expression vals
    
    sol_df.columns = [col.replace("_","-") for col in sol_df.columns]  # GRiNS internally replaces "-" with "_" so that it can name its parameters after the genes
    sol_df = sol_df.reindex(sorted(sol_df.columns),axis=1)

    # QC:
    zero_genes = pd.Series([np.sum(sol_df[col]==0) for col in list(sol_df.columns)])
    minus_genes = pd.Series([np.sum(sol_df[col]<0) for col in list(sol_df.columns)])
    na_genes = pd.Series([np.sum(sol_df[col].isna()) for col in list(sol_df.columns)])
    print(f"There are {np.sum(zero_genes)} zero entries ({np.round(100*np.sum(zero_genes)/(sol_df.shape[0]*sol_df.shape[1]),3)}% of all entries), {np.sum(minus_genes>sol_df.shape[0]*0.01)} genes with more than 1% of entries being negative ({np.round(100*np.sum(minus_genes>sol_df.shape[0]*0.01)/sol_df.shape[1],3)}% of all genes), and {np.sum(na_genes>sol_df.shape[0]*0.01)} genes with more than 1% of entries being NaN ({np.round(100*np.sum(na_genes>sol_df.shape[0]*0.01)/sol_df.shape[1],3)}% of all genes).")

    sol_df = sol_df.fillna(0)
    sol_df[sol_df[:]<0]=0 # There are negative entries for some reason    
    
    # Create the AnnData object:
    print("Create AnnData object...")
    grins_data = ad.AnnData(sparse.csc_matrix(sol_df.values))
    grins_data.obs = info_df
    
    # Add perturbation column
    grins_data.obs["perturbation"] = np.array(["_".join(sorted(list(pert_list[int(i)].keys()))) if i != -1 else "ctrl" for i in grins_data.obs["PertNum"].values])

    grins_data.obs_names = [f"{int(info_df.loc[i,"PertNum"])}_{int(info_df.loc[i,"InitCondNum"])}_{int(info_df.loc[i,"ParamNum"])}_{i}" for i in range(info_df.shape[0])]
    grins_data.var_names = list(sol_df.columns)
    

    return grins_data



def normalize_grins_adata(grins_data : ad.AnnData) -> ad.AnnData:
    """
    Takes the AnnData object just created and normalized it, following the normalization pipeline from the software project.

    Parameters:
    -----------
    grins_data : ad.AnnData
        The unnormalized AnnData object containing the simulation results.
    """
    # Calculate QC metrics:
    print("Calculate QC metrics...")
    sc.pp.calculate_qc_metrics(grins_data,percent_top=[20],inplace=True,log1p=True)

    # Log-normalize the layers:
    print("Normalize Data...")  
    grins_data.layers["log1p"] = grins_data.X.copy().tocsc()
    sc.pp.normalize_total(grins_data, target_sum=None,layer="log1p")

    sc.pp.log1p(grins_data, layer="log1p")
    return grins_data



def grins_ising_to_adata(path_to_data : str, grn_file : str) -> ad.AnnData:
    """
    Takes the state counts saved in a .csv file and turns them into an Anndata object.
    Do note that the on/off states in grins_data.X should not be regarded as counts.

    Parameters:
    -----------
    path_to_data : str
        A path to the file name of the data generated by GRiNS, without the name extension.
    grn_file : str
        The name of the project.

    Returns:
    --------
    grins_data : ad.AnnData
        An AnnData object containing the discrete states of GRiNS.
    """
 
    print(f"Read {path_to_data}.csv...")
    sol_df = pd.read_csv(f"{path_to_data}.csv")
    sol_matrix = np.asarray([list(string) for string in sol_df["State"].values],dtype=int) # if '100101011...', then list(string[1:-1])
    grn = pd.read_csv(f"Data/{grn_file}/{grn_file}.topo",sep=" ")
    grn_genes = sorted(list(set(grn["Source"])|set(grn["Target"])))

    sol_sparse = sparse.csc_matrix(sol_matrix)
    grins_data = ad.AnnData(sol_sparse)
    grins_data.obs_names = sol_df["Initnum"]
    grins_data.var_names = grn_genes
    grins_data.obs["Replicate"] = sol_df["Replicate"].values
    grins_data.obs["Mode"] = sol_df["Mode"].values

    return grins_data


def apply_missingness(grins_data : ad.AnnData, inplace : bool = True) -> ad.AnnData:
    """
    Takes the missing value information from missingness_filter and applies it to a layer.

    Parameters:
    -----------
    grins_data : ad.AnnData
        The grins data object.
    layer : str, optional
        The layer to apply the missingness to. If None, use grins_data.X
    inplace : bool, optional
        Whether or not this should be done inplace (if True, the QC metrics calculated on the raw data will be overwritten!)

    Returns:
    --------
    grins_data : ad.AnnData
        The modified grins data input.
    """
    if inplace:
        data = grins_data
    else:
        data = grins_data.copy()

    print("Applying missingness filter...")
    data.obs.rename(columns=dict(zip([c for c in list(data.obs.columns) if "counts" in c],[f"nm_{c}" for c in list(data.obs.columns) if "counts" in c])),inplace=True) # Rename old QC columns to nonmissing (nm_)
    data.var.rename(columns=dict(zip([c for c in list(data.obs.columns) if "counts" in c],[f"nm_{c}" for c in list(data.obs.columns) if "counts" in c])),inplace=True)
    data.layers["log1p"]=sparse.csc_matrix.multiply(data.layers["log1p"].tocsc(),data.layers["missing_matrix"].tocsc()).tocsc()

    # Calculate QC metrics:
    sc.pp.calculate_qc_metrics(data,percent_top=[20],inplace=True,log1p=True,layer="log1p")
    return data



def missingness_filter(grins_matrix : np.matrix, loc : float = 10, scale : float = 42.2, full_dropouts : float = 0) -> list:
    """
    Inserts missing entries into the raw grins matrix (m cells, n genes) according to the following procedure:
        1. n missing counts l_hat are sampled from an exponential distribution fit to the Replogle dataset (meaning without full dropouts, aka. pct_dropouts<=90)
            - Since the distribution is fit from [0,inf), but the data is in [10,100], so it is first shifted to [0,90].
            - Then, the mean of the counts is calculated as mu, and loc=0 and lambda=scale=1/mu are used (alternatively, it is also possible to fit scipy.stats.expon to the histogram).
            - During sampling, +10 is added to all values, and those that exceed 100 are set to 100; this is also sensible since there is a significant amount of genes with exactly 0 dropouts, which an exponential distribution alone would not capture.
        2. Assuming that a gene with a lower average expression should have more missing entries, both the average expressions across genes and the l_hat are ranked.
        3. Each gene j is assigned the l_hat,j of the same rank, meaning that it should have that many missing entries.
        4. Each entry ij should have a higher missingness probability the lower its expression is; therefore, assign the probability 1/(x_ij+1), and normalize these so that all probabilities add up to 1.
        5. Perform Weighted Random Sampling (WRS) without replacement using an algorithm described by Efraimidis and Spirakis (2005) to set l_hat,j many entries to 0.
    This way, only the entries with the highest expression for low-expression genes will be kept, while high-expression genes will only have few genes removed.

    Parameters:
    -----------
    grins_matrix : np.matrix
        The raw counts.
    loc : float, optional
        How far to the right the distribution should be shifted. 100-max_missingness.
    scale : float, optional
        The scale of the exponential distribution used for missingness sampling.
    full_dropouts : float, optional
        How many genes should have 100% missingness.

    Returns:
    missing_indices : sparse.csc_matrix
        A sparse matrix where all dropout entries are 0 and all entries to be kept are 1.

    Code for params generation (adjust the bins size until distribution fits histogram well):
        plt.hist(100-replogle_data.var["pct_dropout_by_counts"],bins=100,density=True)
        plt.xlim(0,100)
        x = np.linspace(0,100,1000)
        plt.plot(x,expon.pdf(x,loc=10,scale=np.mean(100-replogle_data.var["pct_dropout_by_counts"])))
        plt.plot()
        plt.show()
    """
    expon_params = (loc,scale) # (10,42.2) for Replogle
    missing_matrix = np.ones(grins_matrix.shape)
    gene_mean_order = np.asarray(np.argsort(np.mean(grins_matrix,axis=0))).squeeze()[::-1] # Sorted from high to low expression
    rvs = np.array([x if x < 100 else np.float64(100) for x in expon.rvs(*expon_params,size=grins_matrix.shape[1])]) # pct_dropout_by_counts is on interval [0,100], so all values above 100 (0% dropout) make no sense
    missing_rates = np.sort((grins_matrix.shape[0]*(1-rvs/100)).astype(int)) # The number of missing cells per gene with same rank, 1-x/100 is necessary because rvs contains the percentage of cells not missing
                                                                             # Sorted from low to high number of dropouts
    #print(f"{100*np.sum(missing_rates)/(grins_matrix.shape[0]*grins_matrix.shape[1])}% of entries will become missing") # should be around 56%
    
    for j in range(len(gene_mean_order)): # Start with gene with highest expression level, assign to it the lowest dropout rate
        # Calculate the number of already zero entries (biological zeroes); if there are more than missing_rates[j], no technical zeroes need to be added
        nonzero_rows = np.where(np.asarray(grins_matrix[:,gene_mean_order[j]]).squeeze()!=0)[0]
        
        if grins_matrix.shape[0]-len(nonzero_rows)>=missing_rates[j]:
            continue
        gene_missing_prob = (1/((grins_matrix[nonzero_rows,gene_mean_order[j]]+1)*np.sum(1/(grins_matrix[nonzero_rows,gene_mean_order[j]]+1)))) # Probability for each cell that a gene is missing; add up to 1
        # Weighted random sampling across the cells:
        keys = np.exp(np.random.rand(len(nonzero_rows)),1/gene_missing_prob)
        # Make probability of nonzero positions becoming zero:
        prob_pos = np.zeros(grins_matrix.shape[0])
        # Assign missingness probabilities to remaining nonzero positions:
        prob_pos[nonzero_rows] = keys
        wrs_positions = np.argsort(prob_pos)[::-1][:missing_rates[j]-(grins_matrix.shape[0]-len(nonzero_rows))] # Get a number of entries equal to the lambda with the same rank as the gene mean expression
        if len(wrs_positions)>0:
            missing_matrix[wrs_positions,gene_mean_order[j]]=0

    # Add full dropouts, if desired
    num_dropouts = int(missing_matrix.shape[1]*full_dropouts/100)
    if num_dropouts > 0:
        missing_matrix[:,random.sample(list(range(missing_matrix.shape[1])),num_dropouts)] = 0
    
    #missing_X = sparse.csc_matrix(np.multiply(grins_matrix,missing_matrix))
    
    return sparse.csc_matrix(missing_matrix)#missing_X
    


def main(grn_file : str, is_racipe : bool = True, split_sinks : bool = False, pert_file : str = None, num_replicates : int = 1, mode : str = "async", max_missingness : float = 90, expon_scale : float = 42.2, full_dropouts : float = 0, overwrite=False) -> ad.AnnData:
    """
    Turns either the steady states generated by Racipe or the discrete on/off states generated by Racipe or Ising and turns them into an Anndata object.

    Parameters:
    -----------
    grn_file : str
        The name of the project
    is_racipe : bool
        A boolean indicating whether or not the data is generated through Racipe (True) or Ising (False).
    pert_file : str, optional
        Name of the .pert file, if applicable.
    max_missingness : float, optional
        The maximal percentage of cells for each gene that should be able to be missing.
    expon_scale : float, optional
        The scale of the exponential distribution used for missingness sampling.
    full_dropouts : float, optional
        How many genes should have 100% missingness.
    num_replicates : int, optional
        The number of replicates for the simulation.
    mode : bool, optional
        Indicating whether or not the Ising results are generated using sync or async updates.

    Returns:
    --------
    grins_data : ad.AnnData
        An AnnData object containing the discrete states of GRiNS.

    Examples:
    ---------
    racipe_data = grins_to_adata(path_to_data, is_racipe = True)
    ising_data = grins_to_adata(path_to_data, is_racipe = False, mode="sync")
    """
    assert max_missingness >= 0 and max_missingness <= 100
    assert expon_scale >= 0
    assert full_dropouts >= 0 and full_dropouts <= 100

    if pert_file is not None:
        pert_list = pgrins_prepare_input.extract_pert_info(grn_file,pert_file)
        suffix = "pert"
    else:
        pert_list = []
        suffix = "ctrl"

    for replicate in range(1,num_replicates+1):
        os.makedirs(f"Data/Projects/{grn_file}/{replicate:03}",exist_ok=True)
        # Get file path to data:
        if is_racipe:
            path_to_data = f"Data/SimulResults_Racipe/{grn_file}/{replicate:03}/{grn_file}_steadystate_solutions_{replicate:03}"
        else:
            path_to_data = f"Data/SimulResults_Ising/{grn_file}/{replicate}/{grn_file}_{mode}_SteadyStates"

        return_path = f"Data/Projects/{grn_file}/{replicate:03}/perturb_norm_{suffix}.h5ad"
        # Get AnnData object:
        if not os.path.isfile(return_path) or overwrite:
            print(f"Read {path_to_data}...")
            if is_racipe:
                grins_data = grins_racipe_to_adata(grn_file,path_to_data,split_sinks=split_sinks,replicate=replicate,pert_list=pert_list) 
            else:
                grins_data = grins_ising_to_adata(path_to_data, grn_file) 
            
            print("Generate missing indices...")
            if pert_list == []:
                grins_data.layers["missing_matrix"] = missingness_filter(pd.DataFrame(grins_data.X.todense()).values,loc=100-max_missingness,scale=expon_scale,full_dropouts=full_dropouts)
            else:
                grins_data.layers["missing_matrix"] = scipy.sparse.vstack([missingness_filter(pd.DataFrame(grins_data[grins_data.obs["PertNum"]==i].X.todense()).values,loc=100-max_missingness,scale=expon_scale,full_dropouts=full_dropouts) for i in tqdm(range(-1,len(pert_list)))])

            grins_data.X = sparse.csc_matrix.multiply(grins_data.X.tocsc(),grins_data.layers["missing_matrix"].tocsc()).tocsc()#apply_missingness(grins_data)

            if is_racipe:
                grins_data = normalize_grins_adata(grins_data)    
            else:
                grins_data = grins_ising_to_continuous(grins_data,exp_data)

            # Save the object:
            print(f"Save the AnnData object to {return_path}...")
            grins_data.write_h5ad(
                f"{return_path}"
            ) 
        else:
            print("Done!")


